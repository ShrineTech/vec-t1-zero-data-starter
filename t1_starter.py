# %% [markdown]
# # Virtual Embryo Challenge, Task 1: zero-data starter (SYNTHETIC data only)
#
# Build and test a full T1 pipeline **before** you register or download anything:
#
# 1. generate a synthetic dataset in the documented T1 file layout (optionally on the real public
#    32,285-gene panel, which is public metadata, not data);
# 2. run two baselines: `copy_last` (the official floor) and `composition_shift` (a simple
#    composition-aware baseline);
# 3. validate each prediction against the documented submission contract, including the two silent
#    killers: wrong normalisation and wrong gene order;
# 4. score with the official `veckit` metric functions and the documented 0-100 skill map.
#
# **Nothing here is challenge data.** Synthetic numbers say nothing about the real board.
# Runs as a script (`python t1_starter.py`) or cell by cell in Jupyter / Colab / VS Code (`# %%` cells).

# %%
